using UnityEngine;
using UnityEngine.UI;

// Runtime-only component. Reads the already validated HVACDashboardUI fields.
// It NEVER simulates AUTOSAR HVAC or overrides received HVAC state.
// Outdoor weather is visual until an external-temperature topic is added to Simulink.
public sealed class HVACImmersiveRuntime : MonoBehaviour
{
    public enum Weather { HotSun = 0, Rain = 1, Fog = 2, Snow = 3 }

    [Header("Existing MATLAB/ROS 2 bridge state")]
    public HVACDashboardUI dashboard;

    [Header("UI references (generated by the editor builder)")]
    public Text targetText, cabinText, outsideText, heaterText, coolerText, maintainText;
    public Text rosText, sensorText, commText, weatherText, explanationText, speedText, noticeText;
    public Image heaterTile, coolerTile, maintainTile, weatherHighlight;
    public Button minusButton, plusButton, sunnyButton, rainyButton, foggyButton, snowyButton, autoTourButton;

    [Header("Scene motion and climate")]
    public Transform[] roadSections;
    public Transform wheel;
    public Transform[] airStreaks;
    public Renderer[] airRenderers;
    public ParticleSystem rainParticles;
    public ParticleSystem snowParticles;
    public Light sun;
    public float sectionLength = 36f;
    public float simulatedDrivingKmh = 78f;
    public bool autoWeatherTour = false;
    public float autoWeatherIntervalSeconds = 30f;
    public Weather currentWeather = Weather.HotSun;

    private float tourClock;
    private float roadClock;
    private MaterialPropertyBlock airBlock;
    private Color nextAirColor = Color.clear;
    private bool lastAirVisible;
    private Weather appliedWeather = (Weather)(-1);
    private readonly Color neutral = new Color(.12f, .19f, .26f, .95f);
    private readonly Color heatColor = new Color(.97f, .38f, .09f, .95f);
    private readonly Color coolColor = new Color(.06f, .55f, .98f, .95f);
    private readonly Color holdColor = new Color(.03f, .63f, .43f, .95f);

    private void Awake()
    {
        if (dashboard == null) dashboard = GetComponent<HVACDashboardUI>();
        if (minusButton != null) minusButton.onClick.AddListener(() => ChangeSetpoint(-.5f));
        if (plusButton != null) plusButton.onClick.AddListener(() => ChangeSetpoint(.5f));
        if (sunnyButton != null) sunnyButton.onClick.AddListener(() => ChooseWeather(Weather.HotSun));
        if (rainyButton != null) rainyButton.onClick.AddListener(() => ChooseWeather(Weather.Rain));
        if (foggyButton != null) foggyButton.onClick.AddListener(() => ChooseWeather(Weather.Fog));
        if (snowyButton != null) snowyButton.onClick.AddListener(() => ChooseWeather(Weather.Snow));
        if (autoTourButton != null) autoTourButton.onClick.AddListener(() => { autoWeatherTour = !autoWeatherTour; tourClock = 0f; });
        airBlock = new MaterialPropertyBlock();
        ApplyWeather();
    }

    public void ChangeSetpoint(float delta)
    {
        if (dashboard != null)
            dashboard.targetTempC = Mathf.Clamp(Mathf.Round((dashboard.targetTempC + delta) * 2f) * .5f, 16f, 30f);
    }

    public void ChooseWeather(Weather next)
    {
        autoWeatherTour = false;
        currentWeather = next;
        tourClock = 0f;
        ApplyWeather();
    }

    private void Update()
    {
        if (autoWeatherTour)
        {
            tourClock += Time.deltaTime;
            if (tourClock >= Mathf.Max(10f, autoWeatherIntervalSeconds))
            {
                tourClock = 0f;
                currentWeather = (Weather)(((int)currentWeather + 1) % 4);
                ApplyWeather();
            }
        }
        if (currentWeather != appliedWeather) ApplyWeather();
        AnimateRoad();
        AnimateAir();
        UpdateHud();
    }

    private void AnimateRoad()
    {
        // The car stays at the origin. Streaming roadside segments move toward it.
        // This is a safe VISUAL driving loop, not physics/vehicle-control software.
        float metersPerSecond = simulatedDrivingKmh / 3.6f;
        float step = metersPerSecond * Time.deltaTime;
        roadClock += Time.deltaTime;
        if (roadSections != null)
            foreach (Transform item in roadSections)
            {
                if (item == null) continue;
                item.localPosition -= new Vector3(0f, 0f, step);
                if (item.localPosition.z < -sectionLength)
                    item.localPosition += new Vector3(0f, 0f, roadSections.Length * sectionLength);
            }
        if (wheel != null) wheel.localRotation = Quaternion.Euler(0f, 0f, Mathf.Sin(roadClock * .45f) * 4f);
    }

    private void AnimateAir()
    {
        if (dashboard == null) return;
        bool heating = dashboard.rosConnected && dashboard.heaterOn && !dashboard.sensorFault;
        bool cooling = dashboard.rosConnected && dashboard.acOn && !dashboard.sensorFault;
        bool visible = heating || cooling;
        Color color = heating ? new Color(1f, .45f, .08f) : new Color(.06f, .65f, 1f);
        if (visible != lastAirVisible || (visible && color != nextAirColor))
        {
            lastAirVisible = visible;
            nextAirColor = color;
            if (airRenderers != null)
                foreach (Renderer r in airRenderers)
                    if (r != null) r.enabled = visible;
        }
        if (!visible || airStreaks == null) return;
        // Sinusoidal airflow motion around vents. HVAC state remains Simulink-authored.
        for (int i = 0; i < airStreaks.Length; i++)
        {
            Transform t = airStreaks[i];
            if (t == null) continue;
            float phase = (Time.time * 2.2f + i * .31f);
            t.localPosition = new Vector3(t.localPosition.x, 1.30f + .13f * Mathf.Sin(phase),
                .94f - .22f * Mathf.Repeat(phase * .36f, 1f));
            Renderer r = airRenderers != null && i < airRenderers.Length ? airRenderers[i] : null;
            if (r == null) continue;
            r.GetPropertyBlock(airBlock);
            airBlock.SetColor("_BaseColor", color);
            airBlock.SetColor("_Color", color);
            airBlock.SetColor("_EmissionColor", color * 1.5f);
            r.SetPropertyBlock(airBlock);
        }
    }

    private void ApplyWeather()
    {
        appliedWeather = currentWeather;
        if (rainParticles != null)
        {
            var em = rainParticles.emission;
            em.enabled = currentWeather == Weather.Rain;
            if (currentWeather == Weather.Rain && !rainParticles.isPlaying) rainParticles.Play();
        }
        if (snowParticles != null)
        {
            var em = snowParticles.emission;
            em.enabled = currentWeather == Weather.Snow;
            if (currentWeather == Weather.Snow && !snowParticles.isPlaying) snowParticles.Play();
        }
        Color ambient;
        Color fog;
        if (currentWeather == Weather.HotSun)
        {
            ambient = new Color(.61f, .70f, .82f);
            fog = new Color(.67f, .77f, .89f);
            if (sun != null) { sun.intensity = 1.35f; sun.color = new Color(1f, .90f, .72f); }
            RenderSettings.fogDensity = .002f;
        }
        else if (currentWeather == Weather.Rain)
        {
            ambient = new Color(.35f, .45f, .60f);
            fog = new Color(.35f, .48f, .61f);
            if (sun != null) { sun.intensity = .55f; sun.color = new Color(.77f, .85f, 1f); }
            RenderSettings.fogDensity = .006f;
        }
        else if (currentWeather == Weather.Fog)
        {
            ambient = new Color(.61f, .66f, .70f);
            fog = new Color(.66f, .70f, .73f);
            if (sun != null) { sun.intensity = .42f; sun.color = Color.white; }
            RenderSettings.fogDensity = .021f;
        }
        else
        {
            ambient = new Color(.69f, .75f, .81f);
            fog = new Color(.76f, .83f, .90f);
            if (sun != null) { sun.intensity = .7f; sun.color = new Color(.83f, .91f, 1f); }
            RenderSettings.fogDensity = .011f;
        }
        RenderSettings.ambientMode = UnityEngine.Rendering.AmbientMode.Flat;
        RenderSettings.ambientLight = ambient;
        RenderSettings.fog = true;
        RenderSettings.fogMode = FogMode.Exponential;
        RenderSettings.fogColor = fog;
        if (Camera.main != null) Camera.main.backgroundColor = fog;
    }

    private void UpdateHud()
    {
        if (dashboard == null) return;
        Set(targetText, dashboard.targetTempC.ToString("F1") + " °C");
        Set(cabinText, dashboard.cabinTempC.ToString("F1") + " °C");
        float outdoor = OutdoorTemperature();
        Set(outsideText, outdoor.ToString("F1") + " °C");
        Set(weatherText, WeatherLabel());
        Set(speedText, Mathf.RoundToInt(simulatedDrivingKmh) + " km/h");
        bool ready = dashboard.rosConnected;
        bool heat = ready && dashboard.heaterOn;
        bool cool = ready && dashboard.acOn;
        bool maintain = ready && dashboard.maintainOn;
        Set(heaterText, heat ? "ACTIF" : "INACTIF");
        Set(coolerText, cool ? "ACTIF" : "INACTIF");
        Set(maintainText, maintain ? "ACTIF" : "INACTIF");
        if (heaterTile != null) heaterTile.color = heat ? heatColor : neutral;
        if (coolerTile != null) coolerTile.color = cool ? coolColor : neutral;
        if (maintainTile != null) maintainTile.color = maintain ? holdColor : neutral;
        Set(rosText, ready ? "ROS 2 : DONNEES RECUES" : "ROS 2 : EN ATTENTE");
        Set(sensorText, ready ? (dashboard.sensorFault ? "DEFAUT CAPTEUR !" : "CAPTEUR : OK") : "CAPTEUR : EN ATTENTE");
        // Actual CommLost is not assured unless Simulink publishes /hvac/comm_lost.
        Set(commText, !ready ? "TELEMETRIE : ABSENTE" : dashboard.commLost ? "COMMUNICATION PERDUE" : "COMMUNICATION : NON SIGNALEE EN DEFAUT");
        string explanation;
        if (!ready) explanation = "Demarrez HVAC_Bridge_Start_ROS, puis Simulink. Les boutons restent disponibles, mais aucune action HVAC reelle n'est encore confirmee.";
        else if (dashboard.sensorFault) explanation = "SECURITE ACTIVE - Defaut capteur signale par AUTOSAR. Les commandes HVAC doivent rester dans l'etat sur confirme par Simulink.";
        else if (heat) explanation = "AUTOSAR commande le CHAUFFAGE. Habitacle : " + dashboard.cabinTempC.ToString("F1") + " °C / consigne : " + dashboard.targetTempC.ToString("F1") + " °C.";
        else if (cool) explanation = "AUTOSAR commande la CLIMATISATION. Habitacle : " + dashboard.cabinTempC.ToString("F1") + " °C / consigne : " + dashboard.targetTempC.ToString("F1") + " °C.";
        else if (maintain) explanation = "AUTOSAR est en MAINTIEN : chauffage et climatisation sont inactifs selon la logique d'hysteresis.";
        else explanation = "Etats HVAC recus; le controleur determine le comportement suivant.";
        Set(explanationText, explanation);
        Set(noticeText, "Meteo et conduite = visualisation Unity. Temperature exterieure NON transmise a ThermalPlant.");
        if (autoTourButton != null)
        {
            Text child = autoTourButton.GetComponentInChildren<Text>();
            if (child != null) child.text = autoWeatherTour ? "TOUR AUTO : ON" : "TOUR AUTO : OFF";
        }
    }

    private float OutdoorTemperature()
    {
        switch (currentWeather)
        {
            case Weather.HotSun: return 34f;
            case Weather.Rain: return 7f;
            case Weather.Fog: return 5f;
            default: return -4f;
        }
    }

    private string WeatherLabel()
    {
        switch (currentWeather)
        {
            case Weather.HotSun: return "SOLEIL / CANICULE";
            case Weather.Rain: return "PLUIE / FRAICHEUR";
            case Weather.Fog: return "BRUME / FRAICHEUR";
            default: return "NEIGE / FROID";
        }
    }

    private static void Set(Text text, string value)
    {
        if (text != null && text.text != value) text.text = value;
    }
}
